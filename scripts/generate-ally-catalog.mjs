import fs from 'node:fs/promises';

const source = JSON.parse(await fs.readFile('docs/skills-redesign/skills_redesign.json', 'utf8'));
const definitions = Object.fromEntries(Object.entries(source.allies).map(([role, skills]) => [role, skills.map((skill) => {
  const definition = {
    id: skill.id, owner: skill.owner, kind: skill.kind, name: skill.name, fr: skill.fr, ar: skill.ar,
    description: skill.desc, iconFile: skill.icon_file, cooldown: skill.cd || 0, mana: skill.mana || 0,
    mechanics: skill.mech, auto: skill.auto || '', priority: skill.priority, failsafe: Boolean(skill.failsafe),
    signature: Boolean(skill.signature), legacyId: skill.old && !skill.old.startsWith('(') ? skill.old : null,
    duration: Number(skill.mech.match(/(?:for|lasts) ([\d.]+)s/)?.[1] || 0),
  };
  // The JSON's +/- marks describe prose direction (e.g. -18% damage taken);
  // runtime values are effect magnitudes consumed by the corresponding hook.
  if (skill.vals) definition.values = (skill.vals.match(/[+-]?\d+(?:\.\d+)?/g) || []).map((value) => Math.abs(Number(value)));
  if (skill.icon_source !== 'NEW') definition.art = Number(skill.icon_source.match(/icon-(\d+)/)[1]);
  return definition;
})]));
const messages = Object.values(source.allies).flat().flatMap((skill) => [[skill.name, skill.fr, skill.ar], [skill.desc, skill.desc, skill.desc]]);
const output = `// Generated by scripts/generate-ally-catalog.mjs from skills_redesign.json. Do not hand-edit.\nexport const ALLY_RULES = ${JSON.stringify(source.rules.ally, null, 2)};\nexport const ALLY_CATALOG = ${JSON.stringify(definitions, null, 2)};\nexport const ALLY_MESSAGES = ${JSON.stringify(messages, null, 2)};\n`;
await fs.mkdir('src/data', { recursive: true });
await fs.writeFile('src/data/allyCatalog.js', output);
console.log(`Generated ${Object.values(definitions).flat().length} ally definitions from the JSON.`);
