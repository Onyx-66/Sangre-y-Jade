import fs from 'node:fs/promises';
import path from 'node:path';

// Only FX metadata is generated here. This is not the missing step-9 skill catalogue.
const source = JSON.parse(await fs.readFile('docs/skills-redesign/skills_redesign.json', 'utf8'));
const schemas = {
  'copal-star': ['speed','pierce','damage','trailSeconds','slowPct'],
  'jade-halo': ['duration','beads','radius','revolutions','revolutionSeconds','hitInterval','damage'],
  'ancestor-flame': ['targets','jumpRange','falloffPct','damage','burnDps','burnSeconds'],
  moonwell: ['duration','radius','slowPct','dps','manaRegen'],
  'censer-wave': ['arcDegrees','range','damage','knockback','confuseSeconds'],
  'verdant-mercy': ['duration','radius','heal'],
  'copal-veil': ['duration','shield','manaReturnPct'],
  'glyph-comet': ['range','width','damage','decalSeconds','dps'],
  'cacao-bloom': ['targets','delay','damage','radius','poisonDps','poisonSeconds'],
  raincaller: ['duration','speed','interval','damage','stunChancePct','stunSeconds'],
  'spirit-familiar': ['duration','interval','damage','manaReturn'],
  'serpent-coil': ['radius','pullSeconds','damage','stunSeconds'],
  'jade-needles': ['needles','damage','delay','splashPct','radius'],
  dreamwalk: ['duration','speedPct','radius','damage'],
  'four-directions': ['damage','pierce','range'],
  'ixchels-mantle': ['duration','manaRegenMult','manaCostReductionPct'],
  'ancestral-echo': ['attackCount','jumpRange'],
  'mana-spring': ['killCount'],
  'lunar-boon': ['freeManaCost'],
  'rooted-meditation': ['standSeconds','manaRegen'],
  'jade-resilience': ['quietSeconds','shieldPerSecond'],
  'spirit-harvest': ['heal','manaReturn'],
  'crescent-blessing': ['interval'],
  'mana-overflow': ['thresholdPct','cooldownRecoveryPct'],
};
export const definitions = source.heroes.ixchel.map(skill => {
  const schema = schemas[skill.id];
  if (!schema) throw new Error(`Missing Ixchel FX parameter schema: ${skill.id}`);
  const numbers = [...skill.mech.matchAll(/\d+(?:\.\d+)?/g)].map(match => Number(match[0]));
  if (numbers.length !== schema.length) throw new Error(`${skill.id}: expected ${schema.length} mechanic numbers, found ${numbers.length}`);
  const params = Object.fromEntries(schema.map((name, index) => [name, numbers[index]]));
  if (skill.id === 'four-directions') {
    if (!skill.mech.startsWith('Four bolts')) throw new Error('Four Directions JSON count changed.');
    params.projectiles = ['one','two','three','four'].indexOf(skill.mech.split(' ')[0].toLowerCase()) + 1;
  }
  return { id:skill.id, kind:skill.kind, brief:skill.vfx, mechanics:skill.mech, values:skill.vals || null, params };
});
await fs.mkdir('src/fx/generated', {recursive:true});
await fs.writeFile('src/fx/generated/ixchel.js', '// Generated by scripts/generate-ixchel-fx.mjs from skills_redesign.json. Do not hand-edit.\nexport const IXCHEL_FX_DEFINITIONS = '+JSON.stringify(definitions,null,2)+';\n');
const items = definitions.flatMap(skill => (skill.kind==='active'?['main','accent']:['proc']).map(still => ({
  file:`fx/${skill.id}/${still}.png`, width:skill.kind==='active'?256:128, height:skill.kind==='active'?256:128,
})));
for (let index=0;index<3;index++) {
  const chunk=items.slice(index*16,index*16+16);
  const manifest={expectedCount:chunk.length,columns:4,rows:4,background:'transparent',outputDir:'public/assets/pixel',
    contactSheet:`docs/skills-redesign/previews/step15/contact-sheet-${index+1}.png`,items:chunk};
  await fs.writeFile(path.join('docs/skills-redesign',`fx-ixchel-sheet-${index+1}.json`),JSON.stringify(manifest,null,2)+'\n');
}
console.log(`Generated ${definitions.length} Ixchel FX definitions and ${items.length} still manifest entries.`);
