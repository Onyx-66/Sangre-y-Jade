// Offline localization build: names and English text remain owned by the specification.
import fs from 'node:fs/promises';
import { skillDescriptions, compatibilityMessages } from '../src/i18n/skill-descriptions.js';

export async function generateSkillMessages() {
 const source=JSON.parse(await fs.readFile(new URL('../docs/skills-redesign/skills_redesign.json',import.meta.url),'utf8'));
 const skills=[...Object.values(source.heroes).flat(),...source.shared,...Object.values(source.allies).flat()];
 const translations=new Map(skillDescriptions.map(([id,...pair])=>[id,pair]));
 if(translations.size!==skills.length||translations.size!==skillDescriptions.length)throw Error('Expected one translation per skill');
 const rows=skills.flatMap(skill=>{
  const pair=translations.get(skill.id);
  if(!pair?.every(text=>text&&text!==skill.desc))throw Error(`Missing description: ${skill.id}`);
  return [[skill.name,skill.fr,skill.ar],[skill.desc,...pair]];
 });
 rows.push(...source.stats.map(skill=>[skill.name,skill.fr,skill.ar]),...compatibilityMessages);
 if(new Set(rows.map(row=>row[0])).size!==rows.length)throw Error('Duplicate localization key');
 return `// Generated by scripts/generate-skill-i18n.mjs; edit skill-descriptions.js for translations.\n// Names and English descriptions are copied verbatim from skills_redesign.json.\nexport const skillMessages = [\n${rows.map(row=>` ${JSON.stringify(row)}, // TODO native review`).join('\n')}\n];\n`;
}
const output=new URL('../src/i18n/skills.js',import.meta.url);
const text=await generateSkillMessages();
if(process.argv.includes('--check')){
 // Git's Windows checkout may use CRLF; content, not checkout line endings,
 // determines whether the generated translations are stale.
 if((await fs.readFile(output,'utf8')).replace(/\r\n/g,'\n')!==text)throw Error('Stale skill translations: run node scripts/generate-skill-i18n.mjs');
 console.log('Skill locale generation: up to date (98 skills, 10 stat names, Ixchel compatibility text).');
}else{
 await fs.writeFile(output,text);
 console.log('Generated skill locale rows with native-review markers.');
}
