import fs from 'node:fs/promises';
const source = JSON.parse(await fs.readFile('docs/skills-redesign/skills_redesign.json', 'utf8'));
// Balance values are extracted strictly from the authoritative catalogue, never duplicated.
const patterns = {
 'atlatl-volley': /^(?<projectiles>\d+) darts, spread (?<spread>[\d.]+) rad, pierce (?<pierce>\d+), (?<damage>\d+) dmg each, range (?<range>\d+)/,
 'featherstorm': /^(?<duration>\d+)s.*?r(?<radius>\d+).*?speed (?<speed>\d+).*?(?<damage>\d+) dmg every (?<interval>[\d.]+)s/,
 'serpent-path': /amplitude (?<amplitude>\d+)\).*?speed (?<speed>\d+), pierce (?<pierce>\d+), (?<damage>\d+) dmg, range (?<range>\d+)/,
 'windstep': /Dash (?<range>\d+)\. (?<damage>\d+) dmg.*?for (?<trailSeconds>\d+)s dealing (?<trailDamage>\d+) dmg per (?<interval>[\d.]+)s\. \+(?<speedPct>\d+)% move speed for (?<duration>\d+)s/,
 'quetzal-flip': /Back-flip (?<range>\d+).*?fire (?<projectiles>\d+) darts.*?(?<damage>\d+) dmg each/,
 'hunter-snare': /r(?<radius>\d+): (?<damage>\d+) dmg and ROOT (?<rootSeconds>\d+)s/,
 'eagle-eye': /^(?<focusSeconds>[\d.]+)s.*?shot: (?<damage>\d+) dmg.*?pierce (?<pierce>\d+), range (?<range>\d+)/,
 'sun-dart': /Ricochet (?<chains>\d+) times \(range (?<range>\d+).*?damage (?<damage>\d+), then \+(?<bouncePct>\d+)%/,
 'storm-nest': /^(?<duration>\d+)s.*?Every (?<interval>[\d.]+)s.*?up to (?<targets>\d+).*?\((?<damage>\d+) dmg/,
 'plume-guard': /^(?<duration>\d+)s.*?next (?<charges>\d+)/,
 'cacao-bomb': /a (?<duration>[\d.]+)s arc.*?within (?<range>\d+)\. Explodes r(?<radius>\d+): (?<damage>\d+) dmg, knockback (?<knockback>\d+)/,
 'forked-flight': /for (?<splitSeconds>[\d.]+)s.*?into (?<projectiles>\d+) homing darts \((?<damage>\d+) dmg/,
 'gale-ring': /r(?<range>\d+)\. (?<damage>\d+) dmg, knockback (?<knockback>\d+).*?\+(?<speedPct>\d+)% move speed for (?<duration>\d+)s/,
 'hunters-trance': /^(?<duration>\d+)s: \+(?<attackSpeedPct>\d+)% attack speed, \+(?<critPct>\d+)%/,
 'skyfall': /^(?<telegraphSeconds>[\d.]+)s.*?Then (?<projectiles>\d+) darts over (?<duration>[\d.]+)s across r(?<range>\d+), (?<damage>\d+) dmg each, impact r(?<radius>\d+)/,
 'kukulkans-breath': /Channel (?<duration>[\d.]+)s.*?at (?<movePct>\d+)% speed\).*?Beam (?<range>\d+) x (?<width>\d+)\. Hits every (?<interval>[\d.]+)s for (?<damage>\d+) dmg/,
 'venomous-darts': /for (?<duration>\d+)s, up to (?<maxStacks>\d+) stacks/,
 'full-quiver': /The (?<attackCount>\d+)th/,
 'fleet-hunter': /within (?<duration>\d+)s/,
 'trophy-hunter': /restores (?<healPct>\d+)% max HP.*?for (?<duration>\d+)s/,
 'steady-aim': /standing still (?<standSeconds>\d+)s/,
};
const definitions = source.heroes.kukul.map(skill => {
 const params = {};
 if (patterns[skill.id]) {
  const match = skill.mech.match(patterns[skill.id]);
  if (!match) throw Error(`Cannot extract mechanics: ${skill.id}: ${skill.mech}`);
  Object.assign(params, Object.fromEntries(Object.entries(match.groups).map(([key,value])=>[key,Number(value)])));
 }
 if (skill.id === 'hunters-focus') params.maxStacks = Number(skill.vals.match(/max (\d+) stacks/)[1]);
 if (skill.id === 'skyfall') params.shakePixels = Number(skill.vfx.match(/shake (\d+)px/)[1]);
 const def = {id:skill.id,owner:skill.owner,kind:skill.kind,name:skill.name,description:skill.desc,icon:skill.icon_file,iconFile:skill.icon_file,fx:skill.id,sfx:{cast:`sfx-${skill.id}-cast`},maxLevel:source.rules.hero_slots[skill.kind].max_skill_level,params,palette:(skill.vfx.match(/#[0-9a-f]{6}/gi)||[]).map(hex=>parseInt(hex.slice(1),16))};
 if (skill.icon_source !== 'NEW') def.art = Number(skill.icon_source.match(/icon-(\d+)/)[1]);
 if (skill.kind === 'active') Object.assign(def,{type:'active',cooldown:skill.cd,mana:skill.mana,damage:params.damage||0,range:params.range||0});
 else {
  const text=skill.id==='trophy-hunter'?skill.vals.split(';')[1]:skill.vals;
  def.values=(text.match(/\d+(?:\.\d+)?/g)||[]).map(Number).slice(0,5);
  if(def.values.length!==5)throw Error(`Missing five levels: ${skill.id}`);
 }
 if(['serpent-path','eagle-eye'].includes(skill.id))def.projectiles=1;
 return def;
});
const messages=source.heroes.kukul.flatMap(skill=>[[skill.name,skill.fr,skill.ar],[skill.desc,skill.desc,skill.desc]]);
await fs.mkdir('src/skills/generated',{recursive:true});
await fs.writeFile('src/skills/generated/kukul.js',`// Generated by scripts/generate-kukul-skills.mjs from skills_redesign.json. Do not hand-edit.\nexport const KUKUL_DEFINITIONS = ${JSON.stringify(definitions,null,2)};\nexport const KUKUL_MESSAGES = ${JSON.stringify(messages,null,2)};\n`);
console.log(`Generated ${definitions.length} Kukul definitions from the JSON.`);
